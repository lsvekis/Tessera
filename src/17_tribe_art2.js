function artGlow(g, x, y, r, col, a) {
  const gr = g.createRadialGradient(x, y, 0, x, y, r);
  gr.addColorStop(0, rgba(col, a)); gr.addColorStop(1, rgba(col, 0));
  g.fillStyle = gr; g.beginPath(); g.arc(x, y, r, 0, Math.PI * 2); g.fill();
}
function artGear(g, x, y, r, n, col, hub) {
  g.save(); g.translate(x, y);
  for (let k = 0; k < n; k++) { g.save(); g.rotate(k / n * Math.PI * 2); poly(g, [[-r * 0.2, -r], [r * 0.2, -r], [r * 0.15, -r * 1.26], [-r * 0.15, -r * 1.26]], col); g.restore(); }
  g.restore();
  circ(g, x, y, r, col); circ(g, x, y, r * 0.62, sh(col, -0.16)); if (hub) circ(g, x, y, r * 0.2, hub);
}
function artLeaf(g, x, y, col) { ell(g, x, y, 4.6, 2.4, col); }
function artGrow(p, d) {
  const cx = p.reduce((s, q) => s + q[0], 0) / p.length, cy = p.reduce((s, q) => s + q[1], 0) / p.length;
  return p.map(([x, y]) => { const dx = x - cx, dy = y - cy, l = Math.hypot(dx, dy) || 1; return [x + dx / l * d, y + dy / l * d]; });
}

